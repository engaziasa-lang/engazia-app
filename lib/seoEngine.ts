export interface SeoPageData {
  slug: string;
  title: string;
  subtitle: string;
  badge: string;
  actionUrl: string;
  imagePath: string;
  article: {
    h1: string;
    intro: string;
    h2_1: string;
    p_1: string;
    h2_2: string;
    p_2: string;
    h2_3: string;
    p_3: string;
  };
  faqs: { q: string; a: string }[];
}

// محرك توليد الـ 30 ألف صفحة (متوافق مع 24 أداة)
export function generateSeoContent(slug: string): SeoPageData {
  const urlPath = (slug || "profit-salla-perfumes").toLowerCase();
  
  // المتغيرات الافتراضية الأساسية
  let toolName = "المنظومة المالية وحاسبة الأرباح";
  let platform = "التجارة الإلكترونية";
  let niche = "المنتجات";
  let actionSlug = "profit";

  // فك تشفير المنصة
  if (urlPath.includes('salla')) platform = "منصة سلة";
  else if (urlPath.includes('zid')) platform = "منصة زد";
  else if (urlPath.includes('shopify')) platform = "شوبيفاي";
  else if (urlPath.includes('woo')) platform = "ووكومرس";

  // فك تشفير المجال (Niche)
  if (urlPath.includes('perfume')) niche = "العطور";
  else if (urlPath.includes('abaya')) niche = "العبايات";
  else if (urlPath.includes('dates')) niche = "التمور";
  else if (urlPath.includes('coffee')) niche = "القهوة المختصة";
  else if (urlPath.includes('electronics')) niche = "الإلكترونيات والأجهزة";
  else if (urlPath.includes('fashion')) niche = "الأزياء والملابس";
  else if (urlPath.includes('cosmetics')) niche = "مستحضرات التجميل";
  else if (urlPath.includes('furniture')) niche = "الأثاث المنزلي";

  // فك تشفير الأداة (توسيع لـ 24 أداة)
  if (urlPath.includes('fees') || urlPath.includes('payment')) {
    toolName = "حاسبة رسوم بوابات الدفع (تابي، تمارا، مدى)";
    actionSlug = "fees";
  } else if (urlPath.includes('whatsapp') || urlPath.includes('crm')) {
    toolName = "أداة استرجاع السلال وإدارة العملاء";
    actionSlug = "whatsapp";
  } else if (urlPath.includes('roas') || urlPath.includes('ads')) {
    toolName = "محلل عائد الإعلانات (ROAS)";
    actionSlug = "roas";
  } else if (urlPath.includes('returns') || urlPath.includes('loss')) {
    toolName = "محلل خسائر المرتجعات والشحن العكسي";
    actionSlug = "returns";
  } else if (urlPath.includes('zatca') || urlPath.includes('invoice')) {
    toolName = "مولد الفواتير الإلكترونية المعتمدة (زاتكا)";
    actionSlug = "invoices";
  } else if (urlPath.includes('policy')) {
    toolName = "مولد السياسات وقوانين التجارة";
    actionSlug = "policy";
  } else if (urlPath.includes('ltv')) {
    toolName = "حاسبة القيمة الدائمة للعميل (LTV)";
    actionSlug = "ltv";
  } else if (urlPath.includes('discount') || urlPath.includes('coupon')) {
    toolName = "حاسبة جدوى أكواد الخصم والعروض";
    actionSlug = "promos";
  }

  // بناء المحتوى الضخم المستهدف للسيو (تم تكثيف الكلمات لتكون غنية بالسيو)
  return {
    slug: urlPath,
    title: `${toolName} لزيادة أرباح متاجر ${niche} على ${platform}`,
    subtitle: `الدليل الشامل 2026: استراتيجيات متقدمة لخفض التكاليف التشغيلية، حساب ضريبة القيمة المضافة 15%، ومضاعفة المبيعات لقطاع ${niche} في السوق السعودي.`,
    badge: `أداة حصرية: متاجر ${niche}`,
    actionUrl: `https://engazia-app.vercel.app/hub/sa/${actionSlug}`,
    imagePath: "/images/tools/tool-1.png", 
    article: {
      h1: `الدليل الاستراتيجي: كيف تكتسح سوق ${niche} عبر ${platform}؟`,
      intro: `يشهد قطاع التجارة الإلكترونية في السعودية، وتحديداً سوق ${niche}، طفرة تاريخية غير مسبوقة تماشياً مع أهداف التحول الرقمي. ومع التسهيلات التقنية واللوجستية التي تقدمها ${platform}، تهافت الآلاف من رواد الأعمال والمستثمرين لتأسيس متاجرهم الرقمية بهدف الاستحواذ على شريحة من هذا السوق الواعد. لكن، خلف هذه الواجهة اللامعة والمبيعات المتدفقة، يكمن التحدي الأكبر الذي يسقط فيه معظم المبتدئين: "الإدارة المالية الدقيقة وتتبع التكاليف". الكثير من المتاجر تحقق مبيعات خيالية على الشاشة، ليتفاجأ التاجر بنهاية الشهر المالي أن السيولة النقدية شبه معدومة، وأن أرباحه تبخرت في مصاريف خفية لم يكن يلقي لها بالاً!`,
      h2_1: `التسعير الذكي وتسعير منتجات ${niche} على ${platform}`,
      p_1: `عملية تسعير ${niche} في السوق السعودي لا تعتمد أبداً على التخمين أو مجرد تقليد المنافسين. إن اتباع سياسة "حرق الأسعار" للاستحواذ السريع على السوق هو انتحار تجاري بطيء. المستهلك اليوم يبحث عن الجودة والموثوقية. من خلال استخدام ${toolName}، ستتمكن من إدخال سعر التكلفة الأصلي، وإضافة تكاليف التشغيل الثابتة (مثل اشتراكات ${platform}) والمتغيرة (مثل تكاليف التغليف الخاص بـ ${niche})، لتقوم الخوارزمية الخاصة بنا في إنجازيا بحساب "نقطة التعادل" الدقيقة. نقطة التعادل هي اللحظة الحاسمة التي يغطي فيها متجرك كافة مصاريفه، وما بعدها يعتبر ربحاً صافياً يدخل حسابك البنكي.`,
      h2_2: `التعامل مع رسوم الدفع وخدمات التقسيط لقطاع ${niche}`,
      p_2: `لنتحدث بلغة الأرقام المباشرة؛ تفعيل خدمات الدفع المؤجل (اشتر الآن وادفع لاحقاً) مثل تابي وتمارا في متجرك على ${platform} يرفع معدل التحويل (Conversion Rate) بأكثر من 30% لمنتجات ${niche}. لكن، هذه الخدمات المتطورة لا تأتي مجاناً، فهي تقتطع نسبة مئوية ورسوماً ثابتة من كل عملية بيع تقوم بها. إذا كان هامش ربحك ضعيفاً وغير مدروس، فإن ربحك الصافي سينهار فوراً عند التسوية. هذه الأداة المتقدمة تقوم بتحليل هيكل الرسوم المعقد بدقة عالية وتخبرك بالرقم الصافي الذي سيودع في حسابك، مما يتيح لك اتخاذ قرارات تسعيرية وتسويقية مبنية على بيانات حقيقية.`,
      h2_3: `أهمية الأتمتة المالية لنجاح متاجر ${niche} المحلية`,
      p_3: `التجارة الإلكترونية الناجحة لا تعترف بالعشوائية. الاعتماد على الجداول اليدوية لإدارة آلاف الطلبات يؤدي إلى أخطاء محاسبية قاتلة تستنزف رأس مالك. نظام إنجازيا يوفر لك بنية تقنية قوية تحاكي الأنظمة المحاسبية الكبرى للشركات. تتولى ${toolName} ضبط العمليات الرقمية خلف الكواليس، وتعمل على حساب الضريبة (ضريبة القيمة المضافة 15%) والرسوم بشكل آلي ولحظي. هذا المستوى من الأتمتة يتيح لك كصاحب عمل التفرغ لتسويق متجرك المتخصص في ${niche} وتقديم خدمة عملاء استثنائية وبناء علامة تجارية قوية تدوم لسنوات.`
    },
    faqs: [
      { q: `كيف تتوافق الأداة مع ${platform}؟`, a: `تم برمجة الخوارزميات وتحديثها باستمرار لتطابق رسوم واشتراكات ${platform} بدقة لضمان عدم وجود أي تسرب مالي.` },
      { q: `هل تناسب المبتدئين في ${niche}؟`, a: `نعم، الواجهة بسيطة جداً وتعطيك التوجيهات والأرقام النهائية دون الحاجة لأي خلفية محاسبية أو مالية معقدة.` },
      { q: `هل تدعم الأداة التحديثات الضريبية في السعودية؟`, a: `بالتأكيد، الأداة متوافقة بشكل تام مع ضريبة القيمة المضافة 15% وأنظمة هيئة الزكاة والضريبة والجمارك (ZATCA).` },
      { q: `كيف يمكنني تقييم حملات التسويق لـ ${niche} باستخدام الأداة؟`, a: `الأداة ترتبط بشكل مباشر بمصاريف التسويق لتعطيك العائد الحقيقي على الإنفاق الإعلاني، لتعرف أي القنوات تجلب لك أرباحاً صافية.` }
    ]
  };
}
